// Writes maintenance/logo.ts: the club's logo (public/logo.png) as a data: address, so the maintenance page is one file that needs
// nothing from the site (which may be the thing that's down). Run again if public/logo.png changes.
import { readFileSync, writeFileSync } from "node:fs";

const png = readFileSync("public/logo.png").toString("base64");
writeFileSync("maintenance/logo.ts", `// Generated by scripts/maintenance-logo.mjs from public/logo.png: don't edit by hand.\nexport const LOGO = "data:image/png;base64,${png}";\n`);
console.log("maintenance/logo.ts written");
